import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { env } from './config/env';
import { requestId } from './middleware/requestId';
import { errorHandler } from './middleware/errorHandler';
import { router as auth } from './modules/auth/auth.routes';
import { router as pr } from './modules/purchase-requests/purchase-requests.routes';
import { router as suppliers } from './modules/suppliers/suppliers.routes';
import { router as po } from './modules/purchase-orders/purchase-orders.routes';
import { router as receipts } from './modules/receipts/receipts.routes';
import { router as invoices } from './modules/invoices/invoices.routes';
import { router as workflows } from './modules/workflows/workflows.routes';
import { router as analytics } from './modules/analytics/analytics.routes';
import { router as audit } from './modules/audit/audit.routes';
import { router as webhooks } from './modules/webhooks/webhooks.routes';
import { router as budgets } from './modules/budgets/budgets.routes';
import { router as tenants } from './modules/tenants/tenants.routes';
import { router as attachments } from './modules/attachments/attachments.routes';
import { router as contracts } from './modules/contracts/contracts.routes';
import { router as billing } from './modules/billing/billing.routes';
import { router as notifications } from './modules/notifications/notifications.routes';
import { AppError } from './utils/errors';

export const app = express();
app.use(requestId, helmet(), cors({ origin: env.corsOrigin }), express.json(), morgan('dev'));
app.use(rateLimit({ windowMs: 60_000, limit: 300 }));

app.get('/api/v1/health', (_req, res) => res.json({ status: 'ok' }));
app.use('/api/v1/auth', auth);
app.use('/api/v1/purchase-requests', pr);
app.use('/api/v1/approvals', workflows);
app.use('/api/v1/suppliers', suppliers);
app.use('/api/v1/purchase-orders', po);
app.use('/api/v1/purchase-orders', receipts);
app.use('/api/v1/invoices', invoices);
app.use('/api/v1/analytics', analytics);
app.use('/api/v1/audit-events', audit);
app.use('/api/v1/webhooks', webhooks);
app.use('/api/v1/budgets', budgets);
app.use('/api/v1', tenants);
app.use('/api/v1', attachments);
app.use('/api/v1/contracts', contracts);
app.use('/api/v1/billing', billing);
app.use('/api/v1/notifications', notifications);
app.use((_req, _res, next) => next(new AppError(404, 'ROUTE_NOT_FOUND', 'The requested endpoint was not found')));
app.use(errorHandler);
